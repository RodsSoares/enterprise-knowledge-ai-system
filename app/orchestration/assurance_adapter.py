"""RV-038B: optional offline gate for an existing EvidencePlanner result.

No semantic verification, LLM call, generation, or automatic promotion.
A complementary search requires a new planner pass before generation.
"""
from dataclasses import dataclass
import json

from app.orchestration.evidence_assurance import AssuranceRequest, validate_assurance
from app.orchestration.contracts import digest


class AssuranceIntegrationError(ValueError):
    pass


@dataclass(frozen=True)
class AssuranceGateResult:
    status: str
    assessment: dict | None
    discovered_unit_ids: tuple[str, ...]
    trace: tuple[dict, ...]

    def to_dict(self):
        return {"status": self.status, "assessment": self.assessment,
                "discovered_unit_ids": list(self.discovered_unit_ids),
                "trace": list(self.trace), "semantic_review": "not_performed"}


def evaluate_planned_bundle(*, question, planning_result, assess, search=None,
                            allowed_units=None, recovery_used=False, max_extra=20):
    """Check a planner bundle, then validate an external assessment.

    assess(request) -> a raw assessment JSON string, generated by a fixture or
    an explicitly configured provider. search(query, top_k) -> catalog units;
    never passes the Golden Set to the assessment boundary.
    """
    if type(recovery_used) is not bool or type(max_extra) is not int or not 1 <= max_extra <= 20:
        raise AssuranceIntegrationError("Invalid recovery configuration")
    if not isinstance(planning_result, dict) or planning_result.get("status") != "planned_pending_review":
        raise AssuranceIntegrationError("Completed planner result required")
    if planning_result.get("question") != question:
        raise AssuranceIntegrationError("Question mismatch")
    bundle = planning_result.get("bundle")
    if not isinstance(bundle, dict) or bundle.get("snapshot_id") != planning_result.get("snapshot_id"):
        raise AssuranceIntegrationError("Snapshot mismatch")
    if not isinstance(bundle.get("bundle_hash"), str) or bundle["bundle_hash"] != digest(
        {k: v for k, v in bundle.items() if k != "bundle_hash"}
    ):
        raise AssuranceIntegrationError("Invalid bundle hash")
    coverage, evidence = bundle.get("coverage"), bundle.get("evidence")
    if not isinstance(coverage, list) or not coverage or not isinstance(evidence, list) or not evidence:
        raise AssuranceIntegrationError("Missing coverage or evidence")
    requirement_ids = []
    for item in coverage:
        if not isinstance(item, dict) or not isinstance(item.get("coverage_id"), str):
            raise AssuranceIntegrationError("Invalid coverage entry")
        requirement_ids.append(item["coverage_id"])
    unit_ids = []
    for item in evidence:
        if not isinstance(item, dict) or not isinstance(item.get("unit_id"), str):
            raise AssuranceIntegrationError("Invalid evidence entry")
        unit_ids.append(item["unit_id"])
    if len(set(unit_ids)) != len(unit_ids) or len(set(requirement_ids)) != len(requirement_ids):
        raise AssuranceIntegrationError("Duplicated evidence or requirements")
    if any(not isinstance(item.get("supports"), list) or not item["supports"] or
           any(not isinstance(s, dict) or s.get("unit_id") not in unit_ids
               for s in item["supports"]) for item in coverage):
        raise AssuranceIntegrationError("Coverage references unknown evidence")
    if recovery_used is False and sum(
        event.get("stage") in ("search", "expansion") for event in planning_result.get("trace", [])
        if isinstance(event, dict)
    ) > 1:
        # Do not infer how many prior complements happened from this trace:
        # the planner's initial search also records an event. The caller must
        # explicitly supply recovery_used=True if a complementary search ran.
        raise AssuranceIntegrationError("Prior recovery must be declared")
    request = AssuranceRequest.create(
        question=question, snapshot_id=bundle["snapshot_id"],
        requirement_ids=requirement_ids, candidate_chunk_ids=unit_ids,
        recovery_used=recovery_used,
    )
    raw = assess(request)
    decision = validate_assurance(raw, request).payload
    action = decision["decision"]
    trace = [{"stage": "assurance", "decision": action,
              "evidence_set_hash": request.payload["evidence_set_hash"]}]
    if action == "APPROVE":
        return AssuranceGateResult("approved_structurally", decision, (), tuple(trace))
    if action == "CLARIFY":
        return AssuranceGateResult("clarification_required", decision, (), tuple(trace))
    if action == "ABSTAIN":
        return AssuranceGateResult("abstained", decision, (), tuple(trace))
    if recovery_used or search is None or allowed_units is None:
        raise AssuranceIntegrationError("Authorized search and catalog required")
    catalog = {u.unit_id: u for u in allowed_units}
    if len(catalog) != len(allowed_units):
        raise AssuranceIntegrationError("Catalog IDs must be unique")
    lookup = decision["lookup"]
    additional = search(lookup["query"], max_extra)
    if not isinstance(additional, (tuple, list)) or len(additional) > max_extra:
        raise AssuranceIntegrationError("Recovery exceeded candidate budget")
    extra_ids = []
    for unit in additional:
        if not hasattr(unit, "unit_id") or catalog.get(unit.unit_id) != unit:
            raise AssuranceIntegrationError("Search returned foreign evidence")
        if unit.unit_id not in extra_ids and unit.unit_id not in unit_ids:
            extra_ids.append(unit.unit_id)
    trace.append({"stage": "authorized_search", "returned_unit_ids": extra_ids})
    # Never claim the original plan covers the new evidence.
    return AssuranceGateResult("replan_required", decision, tuple(extra_ids), tuple(trace))
